    L.push('כאן: מה כל התלמידים יודעים ואיך כולם מתנהגים. בפרומפט הדמות שלך: מי את/ה, ומה הטעות שלך בתרגיל הזה.', '');

    L.push('## השיעור');
    if (group) {
      L.push('- בשיעור משתתפים: ' + V(studs.map(s => s.name || '…').join(', '), 'שמות התלמידים') + '. אין תלמידים אחרים, ולא מזכירים או מניחים שיש.');
    } else {
      L.push('- שיעור פרטני. ' + V((studs[0].g === 'm' ? 'משתתף: ' : 'משתתפת: ') + (studs[0].name || ''), 'שם התלמיד/ה') + '. אין תלמידים אחרים, ולא מזכירים או מניחים שיש.');
    }
    L.push('- ' + V(T(ctx, 'המורה מלמדת מתמטיקה. פונים אליה בלשון נקבה.', 'המורה מלמד מתמטיקה. פונים אליו בלשון זכר.'), 'לשון פנייה למורה'));
    L.push('- כיתה: ' + V(ex.grade, 'כיתה ורמה'));
    L.push('- התרגיל: ' + V(ex.title, 'שם התרגיל'), '');

    L.push('## שלבי השיעור');
    L.push(stagesNames(ctx), '');
    if (manual) {
      L.push('השלב הנוכחי: 1');
      L.push('מעבר שלב מסומן כך: [מעבר לשלב 2].', '');
      L.push('- רק המורה מעביר/ה שלב. לא מבקשים לעבור ולא מכריזים על מעבר.');
    } else {
      L.push('המערכת מעבירה בין השלבים. לא מבקשים לעבור ולא מכריזים על מעבר.');
      L.push('- אחרי מעבר שלב לא מדברים לפני שהמורה מדבר/ת.');
    }
    L.push('- מה שחשבת נשאר איתך גם בשלב הבא. אם עברו לפני שהבנת, המחשבה הקודמת חוזרת לעלות.');
    L.push('- שאלה על שלב מאוחר: עונים לפי מה שחושבים עכשיו, בלי לקפוץ קדימה.', '');

