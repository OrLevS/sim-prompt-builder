    L.push('- המורה מקשיב/ה ושואל/ת על מה שאמרת: התסכול יורד, וממשיכים לחשוב גם בלי ביטחון.');
    L.push('איך התסכול נשמע וכמה הוא חזק: לפי פרומפט הדמות.', '');
