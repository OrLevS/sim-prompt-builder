  function errorHelper(ctx, idx) {
    const st = ctx.students[idx];
    const ex = ctx.exercise;
    const p = st.persona || {};
    const G = (f, m) => (st.g === 'm' ? m : f);
    const L = [];
    L.push('אני בונה סימולציית הוראה במתמטיקה: מורה מנהל/ת שיח עם ' + G('תלמידה וירטואלית', 'תלמיד וירטואלי') + '. אני צריכה הצעות לטעות ש' + G('התלמידה תעשה', 'התלמיד יעשה') + ' בתרגיל.', '');
    L.push('## התרגיל');
    L.push('שם: ' + (ex.title || '—'));
    L.push('כיתה: ' + (ex.grade || '—'));
    L.push('מה כבר למדו:\n' + (ex.learned || '—'));
    L.push('המשימה:\n' + (ex.task || '—'));
    if (has(ex.figure)) L.push('השרטוט: ' + ex.figure);
    if (has(ex.notYet)) L.push('עוד לא למדו:\n' + ex.notYet);
    L.push('הרעיון המתמטי המרכזי: ' + (ex.centralIdea || '—'));
    L.push('הפתרון:\n' + (ex.solution || '—'));
    const stg = ctx.stages.filter(s => has(s.name));
    if (stg.length) L.push('שלבי השיעור:\n' + stg.map((s, i) => (i + 1) + '. ' + s.name + (s.goal ? ' — יעד: ' + s.goal : '')).join('\n'));
    L.push('');
    L.push('## הדמות: ' + (st.name || ''));
    window.PERSONA_FIELDS.forEach(([k, label]) => { if (has(p[k])) L.push(label + ': ' + p[k]); });
    L.push('');
    L.push('## מה אני צריכה');
    L.push('שלוש הצעות לטעות או לתפיסה שגויה ש' + (st.name || 'הדמות') + ' ' + G('עלולה', 'עלול') + ' לעשות בתרגיל הזה. לכל הצעה:');
    L.push('1. הטעות: מה ' + G('עשתה', 'עשה') + ' ומה ' + G('חשבה', 'חשב') + ', במשפט או שניים.');
    L.push('2. למה היא מתאימה דווקא לאישיות הזאת.');
    L.push('3. באיזה שלב של השיעור היא צפויה לצוץ.');
    L.push('4. "להדבקה": 2–4 משפטים בגוף שלישי, שמתארים מה ' + G('היא חושבת', 'הוא חושב') + ' ומה ' + G('היא תגיד', 'הוא יגיד') + ' בהתחלה. בלי לכתוב מה יתקן את הטעות.', '');
    L.push('כללים:');
    L.push('- טעות שתלמידים אמיתיים עושים, ולא טעות חישוב מקרית.');
    L.push('- קשורה לרעיון המתמטי המרכזי, כך שלמורה יש על מה לעבוד.');
    L.push('- מתאימה למה שכבר נלמד, ולא דורשת דרכים שעוד לא נלמדו.');
    L.push('- ההצעות שונות זו מזו באמת.');
    L.push('- עברית פשוטה וקצרה. בלי מבוא ובלי סיכום.');
    return L.join('\n');
  }

